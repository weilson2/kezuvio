const word = (text, x, y, size, fill) => {
  let cursor = x,
    previous = null,
    outlines = "";
  for (const character of text) {
    const glyph = font.charToGlyph(character);
    if (previous)
      cursor +=
        (font.getKerningValue(previous, glyph) * size) / font.unitsPerEm;
    outlines += glyph.getPath(cursor, y, size).toPathData(3);
    cursor += (glyph.advanceWidth * size) / font.unitsPerEm;
    previous = glyph;
  }
  return `<path fill="${fill}" d="${outlines}"/>`;
};
